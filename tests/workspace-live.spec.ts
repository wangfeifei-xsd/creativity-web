  await page.locator('.ant-select-dropdown:visible').getByText('页面租号渠道 · 测试 · 租号业务域', { exact: true }).click()
  await dialog.getByRole('button', { name: '进入工作区' }).click()
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  await page.goto(detailPath)
  await page.getByRole('tab', { name: '接入服务', exact: true }).click()
  await page.getByRole('button', { name: '登记接入服务', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill('租号业务后端')
  await choose(page, dialog, '环境', '测试')
