  await page.getByRole('tab', { name: '接入 Key', exact: true }).click()
  await page.getByRole('button', { name: '创建 Key', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill('租号接入凭据')
  await choose(page, dialog, '环境', '测试')
  await choose(page, dialog, '可调用能力', '执行能力')
  await choose(page, dialog, '接入服务', '租号业务后端 · 测试')
  await dialog.getByLabel('有效期至').fill('2027-10-01T12:00')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
