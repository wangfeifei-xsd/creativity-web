  await activeKey.getByRole('button', { name: '吊销', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('button', { name: '归档渠道', exact: true }).click()
  await page.getByRole('button', { name: '确认归档渠道', exact: true }).click()
